export type Key = keyof typeof strings
export const t = (lang: Lang, key: Key): string => strings[key][lang === 'bg' ? 0 : 1]
export const declarationName = (lang: Lang, d: Declaration): string =>
  t(
    lang,
    d.kind === 'carre'
      ? 'carre'
      : d.cards.length === 3
        ? 'terce'
        : d.cards.length === 4
          ? 'quart'
          : d.cards.length === 5
            ? 'quint'
            : 'sequence',
  )
