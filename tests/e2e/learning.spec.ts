import { expect, test } from './fixture'

test('finishes a lesson, switches language during feedback and restores progress', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Към академията' }).click()
  await expect(page.getByRole('heading', { name: 'Белот академия' })).toBeVisible()
  const submit = page.getByRole('button', { name: 'Провери отговора' })
  await expect(submit).toBeDisabled()
  await page.getByRole('radio', { name: '24', exact: true }).check()
  await submit.click()
  await expect(page.getByText('Опитай пак', { exact: true })).toBeVisible()
  await page.getByRole('radio', { name: '32', exact: true }).check()
  await submit.click()
  await expect(page.getByText('Вярно', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Език', exact: true }).selectOption('en')
  await expect(page.getByText('Correct', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Belot Academy' })).toBeVisible()
  await page.getByRole('button', { name: 'Next lesson' }).click()
  await expect(page.getByRole('heading', { name: 'Partners and seats' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Partners and seats' })).toBeVisible()
  await expect(page.locator('.study-progress')).toContainText('1 / 15')
  await page.goto('/#play')
  await expect(page.getByRole('button', { name: 'Continue learning' })).toBeVisible()
})

test('solves a tactical puzzle on a portrait phone and records both attempts', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/#puzzles')
  await page.getByRole('combobox', { name: 'Език', exact: true }).selectOption('en')
  await page.getByRole('combobox', { name: 'Difficulty', exact: true }).selectOption('intermediate')
  await page
    .getByRole('combobox', { name: 'Choose a puzzle', exact: true })
    .selectOption('load-your-partner')
  await expect(page.getByRole('heading', { name: 'Give your partner points' })).toBeVisible()
  await page.getByRole('radio', { name: '7 Hearts' }).check()
  await page.getByRole('button', { name: 'Check answer' }).click()
  await expect(page.getByText('Try again', { exact: true })).toBeVisible()
  await page.getByRole('radio', { name: '10 Spades' }).check()
  await page.getByRole('button', { name: 'Check answer' }).click()
  await expect(page.getByText('Correct', { exact: true })).toBeVisible()
  await expect(page.locator('.study-progress')).toContainText('1 / 25')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360)
  await page.goto('/#stats')
  await expect(page.locator('.stat-line').filter({ hasText: 'Puzzle accuracy' })).toContainText('50%')
  await expect(page.locator('.stat-learning-row').filter({ hasText: 'Puzzles solved' })).toContainText(
    '1 / 25',
  )
})
